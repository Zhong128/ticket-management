import {test,expect} from '@playwright/test'

test('后台真实业务API配置城市分类演出场次票档并保护管理员',async({page})=>{
    const errors:string[]=[]
    page.on('pageerror',error=>errors.push(error.message))
    await page.goto('/admin/login')
    await page.getByLabel('用户名',{exact:true}).fill('journey-9102')
    await page.getByLabel('密码',{exact:true}).fill('journey-test-pass')
    await page.getByRole('button',{name:'登录管理端'}).click()
    await expect(page.getByRole('heading',{name:'演出运营工作台'})).toBeVisible()

    await page.goto('/admin/cities')
    await page.getByRole('button',{name:'新增城市',exact:true}).click()
    let dialog=page.getByRole('dialog')
    await dialog.getByLabel('城市名称').fill('后台测试城')
    await dialog.getByLabel('城市代码').fill('ADMIN_TEST_CITY')
    await dialog.getByLabel('省份').fill('测试省')
    await dialog.getByRole('button',{name:'保存城市'}).click()
    await expect(dialog).not.toBeVisible()

    await page.goto('/admin/categories')
    await page.getByRole('button',{name:'新增分类',exact:true}).click()
    dialog=page.getByRole('dialog')
    await dialog.getByLabel('分类名称').fill('后台测试音乐会')
    await dialog.getByRole('button',{name:'保存分类'}).click()
    await expect(dialog).not.toBeVisible()

    await page.goto('/admin/events/new')
    await page.getByLabel('演出名称',{exact:true}).fill('隔离后台音乐会')
    await page.getByLabel('艺人名称').fill('隔离测试乐团')
    await page.getByRole('combobox',{name:'城市',exact:true}).selectOption({label:'后台测试城'})
    await page.getByRole('combobox',{name:'分类',exact:true}).selectOption({label:'后台测试音乐会'})
    await page.getByLabel('场馆',{exact:true}).fill('隔离测试剧院')
    await page.getByLabel('演出介绍').fill('<b>后台录入纯文本</b>')
    await page.getByLabel('开售时间',{exact:true}).fill('2026-01-01T10:00')
    await page.getByLabel('停售时间',{exact:true}).fill('2027-01-01T10:00')
    await page.getByLabel('演出开始时间',{exact:true}).fill('2027-01-02T18:00')
    await page.getByLabel('演出结束时间',{exact:true}).fill('2027-01-02T22:00')
    await page.getByRole('combobox',{name:'状态',exact:true}).selectOption('1')
    await page.getByRole('button',{name:/保存演出/}).click()
    await expect(page).toHaveURL(/\/admin\/events$/)

    await page.goto('/admin/sessions')
    await page.getByRole('button',{name:'新增场次',exact:true}).click()
    dialog=page.getByRole('dialog')
    await dialog.getByRole('combobox',{name:'所属演出',exact:true}).selectOption({label:'隔离后台音乐会'})
    await dialog.getByLabel('场次名称').fill('隔离后台晚场')
    await dialog.getByLabel('场次时间').fill('2027-01-02T19:30')
    await dialog.getByRole('button',{name:'保存场次'}).click()
    await expect(dialog).not.toBeVisible()

    await page.goto('/admin/ticket-tiers')
    await page.getByRole('button',{name:'新增票档',exact:true}).click()
    dialog=page.getByRole('dialog')
    await dialog.getByRole('combobox',{name:'演出',exact:true}).selectOption({label:'隔离后台音乐会'})
    await dialog.getByRole('combobox',{name:'场次',exact:true}).selectOption({label:'隔离后台晚场'})
    await dialog.getByLabel('票档名称').fill('隔离后台看台')
    await dialog.getByLabel('原价',{exact:true}).fill('120')
    await dialog.getByLabel('现价',{exact:true}).fill('100')
    await dialog.getByLabel('总库存',{exact:true}).fill('20')
    await dialog.getByLabel('可用库存',{exact:true}).fill('20')
    await dialog.getByRole('button',{name:'保存票档'}).click()
    await expect(dialog).not.toBeVisible()

    await page.goto('/events?name=隔离后台音乐会')
    await expect(page.getByRole('heading',{name:'隔离后台音乐会',exact:true})).toBeVisible()
    await page.goto('/admin/sessions')
    const row=page.getByRole('row').filter({hasText:'隔离后台晚场'})
    await row.getByRole('button',{name:'下架',exact:true}).click()
    await page.getByRole('dialog').getByRole('button',{name:'确认下架'}).click()
    await expect(row).toContainText('已下架')

    await page.goto('/admin/users?username=journey-9102')
    await expect(page.getByRole('row').filter({hasText:'journey-9102'})).toContainText('只读账户')
    expect(errors).toEqual([])
})
